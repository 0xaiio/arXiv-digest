def main():
    path = os.path.join(pu.OUT, "summaries.json")
    data = {}
    if os.path.exists(path):
        try:
            data = json.load(open(path, encoding="utf-8"))
        except Exception:
            data = {}
    added = 0
    for k, v in ADD.items():
        if not k:
            continue
        if not data.get(k):
            data[k] = v
            added += 1
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    os.replace(tmp, path)
    print("summaries.json: +%d -> 共 %d 条" % (added, len(data)))


if __name__ == "__main__":
    main()
