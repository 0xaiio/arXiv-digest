def main():
    os.makedirs(OUT, exist_ok=True)
    sp = os.path.join(OUT, "summaries.json")
    data = json.load(open(sp, encoding="utf-8")) if os.path.exists(sp) else {}
    data.update({pu.short_id(k): v for k, v in SUMMARIES.items()})
    json.dump(data, open(sp, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    np_ = os.path.join(OUT, "rec_notes.json")
    notes = json.load(open(np_, encoding="utf-8")) if os.path.exists(np_) else {}
    for sid, why in SKIP.items():
        if why:
            notes.setdefault(pu.short_id(sid), {})["skip"] = True
            notes[pu.short_id(sid)].setdefault("note", why)
    for sid, n in NOTES.items():
        rec = notes.setdefault(pu.short_id(sid), {})
        rec.pop("skip", None)
        rec.update(n)
    json.dump(notes, open(np_, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("summaries=%d (+%d)  rec_notes=%d (+%d)" % (
        len(data), len(SUMMARIES), len(notes), len(NOTES) + len(SKIP)))


if __name__ == "__main__":
    main()
